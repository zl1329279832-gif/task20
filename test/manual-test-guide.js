/* ===== 手动复现测试说明 ===== */
/*
 * 本文件提供可手动复现的测试步骤, 用于验证数据一致性修复。
 * 前置条件: 通过 python serve.py 启动 HTTP 服务器, 浏览器打开 http://localhost:8080
 *
 * 自动化测试: 打开 http://localhost:8080/test/verification.html
 *
 * ============================================================
 * 测试场景 1: 导入 A 后立即导入 B — 数据不串页
 * ============================================================
 *
 * 步骤:
 *   1. 启动系统, 等待演示数据加载完成
 *   2. 切换到「数据导入」页面
 *   3. 准备两个 CSV 文件:
 *      - data-A.csv: 包含楼栋 B001 的 meter_readings
 *      - data-B.csv: 包含楼栋 B002 的 meter_readings
 *   4. 拖入 data-A.csv, 选择「电表读数」类型, 点击导入
 *   5. 立即(不等待看板完全刷新)拖入 data-B.csv, 选择「电表读数」类型, 点击导入
 *
 * 预期:
 *   - 看板只显示 B002 的数据
 *   - 不出现 B001 的任何数据
 *   - 控制台不报错
 *   - 打开 DevTools 执行:
 *     window._energyApp.dashboardController.data.readings
 *       .map(r => r.building_id)
 *       .filter((v, i, a) => a.indexOf(v) === i)
 *     应该只返回 ['B002']
 *
 * ============================================================
 * 测试场景 2: 快速切换楼栋/楼层/时间段
 * ============================================================
 *
 * 步骤:
 *   1. 进入「分析仪表盘」页面
 *   2. 在 1 秒内快速切换:
 *      楼栋下拉框: 全部 -> B001 -> B002 -> 全部
 *      时间粒度: 月 -> 日 -> 季 -> 年 -> 月
 *      日期范围: 改为最近30天 -> 改为最近90天 -> 改为全部
 *
 * 预期:
 *   - 最终看板显示的是最后一次筛选的结果
 *   - 不出现闪烁或中间状态的数据
 *   - 打开 DevTools 执行:
 *     JSON.stringify(window._energyApp.filter.get())
 *     应与最后一次选择的筛选条件一致
 *   - 同比/环比数字与手动计算一致
 *
 * ============================================================
 * 测试场景 3: 保存方案再恢复
 * ============================================================
 *
 * 步骤:
 *   1. 设置筛选条件: 楼栋=B001, 时间=2025-01-01~2025-06-30
 *   2. 点击「保存方案」, 命名为 "方案A"
 *   3. 记住看板上的总能耗和总电费数字
 *   4. 切换筛选条件: 楼栋=B002, 时间=全部
 *   5. 确认看板数字已变化
 *   6. 点击「加载方案」, 选择 "方案A"
 *
 * 预期:
 *   - 恢复后看板数据与步骤3完全一致
 *   - 筛选控件自动回到 B001 + 2025-01-01~2025-06-30
 *
 * 步骤(数据变更后):
 *   7. 切换到「数据导入」, 导入新的 meter_readings 数据
 *   8. 回到仪表盘, 点击「加载方案」
 *   9. 观察 "方案A" 旁边是否有 ⚠ 标记
 *
 * 预期:
 *   - 如果数据已变更, 方案名称旁显示 "⚠ 数据已变更" 警告
 *   - 点击加载时弹出 toast 提示数据已变更
 *
 * ============================================================
 * 测试场景 4: 导出报告一致性
 * ============================================================
 *
 * 步骤:
 *   1. 设置筛选条件: 楼栋=B001, 时间=最近一年
 *   2. 等待看板完全渲染
 *   3. 记录看板上的: 总能耗、总电费、同比变化、环比变化
 *   4. 点击「导出报告」
 *   5. 打开导出的 HTML 文件
 *
 * 预期:
 *   - 报告中的总能耗、总电费与看板完全一致
 *   - 同比/环比数字与看板一致
 *   - 报告底部的"数据版本"、"查询ID"、"筛选校验码"均存在
 *   - 报告筛选描述与实际筛选条件一致
 *
 * 步骤(切换后导出):
 *   6. 快速切换楼栋为 B002
 *   7. 等看板稳定后立即点击「导出报告」
 *
 * 预期:
 *   - 导出的报告显示 B002 的数据, 不包含 B001
 *
 * ============================================================
 * 测试场景 5: 低置信度字段映射阻断
 * ============================================================
 *
 * 步骤:
 *   1. 准备一个 CSV 文件, 列名完全无关:
 *      col_a, col_b, col_c
 *      1, 2, 3
 *   2. 拖入文件, 选择「楼栋」类型
 *
 * 预期:
 *   - 字段映射区域显示所有映射为「低」置信度
 *   - 出现红色错误提示: "以下字段映射置信度过低..."
 *   - 「导入」按钮被禁用(灰色, 不可点击)
 *   - 无法执行导入操作
 *
 * ============================================================
 * 快速验证命令 (DevTools Console)
 * ============================================================
 *
 * // 检查 Worker Manager 版本
 * const wm = window._energyApp.workerManager;
 * console.log('session:', wm.getSessionVersion(), 'query:', wm.getQueryId());
 *
 * // 检查看板缓存
 * const dc = window._energyApp.dashboardController;
 * console.log('cached report:', !!dc._cachedReportData);
 * console.log('active filter:', JSON.stringify(dc._activeFilterSnapshot));
 *
 * // 检查导出报告使用的数据是否和看板一致
 * const report = dc.getReportData();
 * const currentFilter = JSON.stringify(window._energyApp.filter.get());
 * const reportFilter = JSON.stringify(report.filter);
 * console.log('filter match:', currentFilter === reportFilter);
 *
 * // 检查方案指纹
 * const storage = window._energyApp.storage;
 * const fp = await storage.computeDataFingerprint();
 * console.log('fingerprint:', JSON.stringify(fp, null, 2));
 *
 * ============================================================
 * 测试场景 6: 碳排因子导入 + 碳排放计算
 * ============================================================
 *
 * 步骤:
 *   1. 启动系统, 等待演示数据加载
 *   2. 切换到「数据导入」, 选择「碳排因子」类型
 *   3. 准备 CSV:
 *      factor_id,building_id,period_type,factor,effective_date,source
 *      CF1,all,sharp_peak,1.102,2025-01-01,grid
 *      CF2,all,peak,0.997,2025-01-01,grid
 *      CF3,all,flat,0.725,2025-01-01,grid
 *      CF4,all,valley,0.483,2025-01-01,grid
 *   4. 导入文件
 *   5. 切换到「分析仪表盘」, 查看碳排放热力图和碳排排行
 *
 * 预期:
 *   - 字段映射全部高置信度
 *   - 碳排放热力图显示各楼栋×时段的碳排强度
 *   - 碳排排行显示 top-15 设备碳贡献
 *   - 策略沙盘中的总碳排放卡片有数值
 *
 * ============================================================
 * 测试场景 7: 策略沙盘全流程
 * ============================================================
 *
 * 步骤:
 *   1. 导航到「策略沙盘」
 *   2. 观察已有的「基线方案」和「综合优化方案」
 *   3. 点击「全部评估」
 *   4. 勾选两个策略的对比复选框
 *   5. 观察策略对比图表
 *   6. 点击「新建策略」, 调整参数创建新策略
 *   7. 再次「全部评估」
 *   8. 点击「导出对比报告」
 *
 * 预期:
 *   - 基线方案碳减排率 ≈ 0%
 *   - 优化方案碳减排率 > 0%
 *   - 策略对比图表正确显示分组柱图
 *   - 导出的 HTML 报告包含所有策略数据
 *
 * ============================================================
 * 测试场景 8: 快速筛选切换下的策略一致性
 * ============================================================
 *
 * 步骤:
 *   1. 进入「分析仪表盘」, 等看板渲染完成
 *   2. 快速切换楼栋: 全部 → B001 → B002 → 全部 (每次间隔<200ms)
 *   3. 等看板稳定后, 记录碳排放数值
 *   4. 切到「策略沙盘」, 点击「全部评估」
 *   5. 再切回仪表盘, 快速切换楼栋
 *   6. 观察碳排热力图和策略预测vs实际趋势是否一致
 *
 * 预期:
 *   - 最终显示的碳排数据与最后一次筛选一致
 *   - 策略评估结果与当前筛选条件匹配
 *   - 无闪烁或数据残留
 */
